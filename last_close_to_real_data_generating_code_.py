    for et in [x for x in [truth.extub_time, truth.reintub_time] if x is not None]:
        if random.random() < 0.35:
            med = weighted_choice([(m, m["base_p"]) for m in FORMULARY])
            ot = et + pd.Timedelta(hours=random.randint(-6, 6))
