def clamp(x, lo, hi):
    return max(lo, min(hi, x))

def weighted_choice(items):
    total = sum(w for _, w in items)
    r = random.random() * total
    cum = 0.0
    for v, w in items:
        cum += w
        if r <= cum:
            return v
    return items[-1][0]

def pick_from_mixture(mix):
    r = random.random()
    cum = 0.0
    for prob, a, b in mix:
        cum += prob
        if r <= cum:
            return random.randint(a, b)
    return random.randint(mix[-1][1], mix[-1][2])

