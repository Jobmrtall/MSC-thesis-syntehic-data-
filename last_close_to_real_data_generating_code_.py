        if med["freq"] == "infusion":
            step_h = 4
        elif med["freq"] == "q6h":
            step_h = 6
        elif med["freq"] == "q12h":
            step_h = 12
        else:
            step_h = 24

        end_time = stop if stop is not None else discharge
        t = start
        while t < end_time:
            given = 1
            reason = None
            if random.random() < 0.06:
                given = 0
                reason = weighted_choice([("patient unavailable", 0.4), ("low BP", 0.2), ("contraindicated", 0.2), ("other", 0.2)])
