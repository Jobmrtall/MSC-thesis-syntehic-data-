        if med["freq"] == "infusion":
            if random.random() < 0.35:
                stop = start + pd.Timedelta(hours=random.randint(12, 72))
        else:
            if random.random() < 0.25:
                stop = start + pd.Timedelta(days=random.randint(2, 7))
